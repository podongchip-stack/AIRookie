def standard_names(span_text: str) -> list[tuple[int, str]]:
    """구간 안에서 찾은 (구간 안 글자 위치, 표준명) 목록. 위치 순서이며 같은 표준명은 첫 위치만 남긴다."""
    found = []
    for phrase, name in _PATTERNS:
        start = span_text.find(phrase)
        while start != -1:
            found.append((start, len(phrase), name))
            start = span_text.find(phrase, start + 1)
    found.sort(key=lambda f: (f[0], -f[1]))

    chosen: list[tuple[int, str]] = []
    taken_until = 0
    seen: set[str] = set()
    for start, length, name in found:
        if start < taken_until:
            continue
        taken_until = start + length
        if name not in seen:
            seen.add(name)
            chosen.append((start, name))
    return chosen
